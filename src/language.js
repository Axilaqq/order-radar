// Определение украинского языка в объявлении.
//
// Опора — буквы, которых нет в соседнем алфавите:
//   украинские і, ї, є, ґ — в русском их нет вообще;
//   русские    ы, э, ъ, ё — в украинском их нет вообще.
//
// Считаем и то и другое, а не ищем одну букву: в русском тексте может
// попасться украинское название («склад у місті Київ»), и пара букв не должна
// отправлять заказ в корзину. Решает перевес.
//
// Дополнительно — корни слов, которые в русском пишутся иначе («розробка» /
// «разработка», «налаштування» / «настройка»). Нужны для коротких текстов,
// где ни одной из четырёх украинских букв просто не встретилось. Этот признак
// срабатывает только при полном отсутствии русских букв.
//
// ОГРАНИЧЕНИЕ: короткий украинский текст без характерных букв и без известного
// корня не распознаётся — например заголовок «BLENDER модулюваня» сам по себе.
// На практике это не мешает: проверяется заголовок ВМЕСТЕ с описанием, и там
// признаки находятся. Замер 01.09.2026 на 81 заказе Freelancehunt: поймано 49,
// на 55 заказах Инфостарта ложных срабатываний ноль.
const UA_ONLY = /[іїєґ]/gi;
const RU_ONLY = /[ыэъё]/gi;
const UA_STEMS = /розроб|налаштув|оновлен|замовлен|створен|виготов|звернен|надсил|потріб|шука[юєм]/i;

const UA_MIN_CHARS = 2;

export function looksUkrainian(text = '') {
  const s = String(text);
  const ua = (s.match(UA_ONLY) || []).length;
  const ru = (s.match(RU_ONLY) || []).length;

  // Явный перевес украинских букв.
  if (ua >= UA_MIN_CHARS && ua > ru) return true;
  // Есть украинская буква и нет ни одной русской — сомнений не остаётся.
  if (ua >= 1 && ru === 0) return true;
  // Букв не нашлось, но есть корень, которого в русском не бывает.
  if (ru === 0 && UA_STEMS.test(s)) return true;
  return false;
}
